import { test, expect } from '@playwright/test'
import { login, requireLocalTestApp, itemPhoto } from '../../e2e-helpers.js'

test.describe('Wardrobe create, search, edit and delete (end-to-end)', () => {
  requireLocalTestApp(test)
  test('WOP-E01: create, find, edit and delete a wardrobe item with persisted changes', async ({ page }) => {
    await login(page, 'wardrobe.student@example.invalid')
    await page.goto('/wardrobe')
    await page.getByRole('link', { name: /Add clothing/ }).click()
    await page.locator('input[type="file"]').setInputFiles(itemPhoto)
    await page.getByPlaceholder('e.g. White linen shirt').fill('Everyday linen shirt')
    await page.getByLabel('Material', { exact: false }).fill('Linen')
    await page.getByText('Select colours', { exact: true }).click()
    await page.getByRole('checkbox', { name: 'White', exact: true }).check()
    await page.getByRole('checkbox', { name: 'Black', exact: true }).check()
    await page.getByRole('checkbox', { name: 'Minimalist', exact: true }).check()
    await page.getByRole('button', { name: 'Add to my wardrobe', exact: true }).click()
    await expect(page).toHaveURL(/\/wardrobe$/)
    await expect(page.getByRole('heading', { name: 'Everyday linen shirt', exact: true })).toBeVisible()
    await page.reload()
    await page.getByRole('searchbox', { name: 'Search your wardrobe' }).fill('Black')
    await expect(page.getByRole('heading', { name: 'Everyday linen shirt', exact: true })).toBeVisible()
    await page.getByRole('link', { name: 'Edit piece', exact: true }).click()
    await page.getByPlaceholder('e.g. White linen shirt').fill('Updated everyday shirt')
    await page.getByPlaceholder('e.g. Cotton, linen, denim').fill('Cotton')
    await page.getByRole('button', { name: 'Save changes', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Updated everyday shirt', exact: true })).toBeVisible()
    const saved = await (await page.request.get('/api/wardrobe/items')).json()
    expect(saved.items).toHaveLength(1)
    expect(saved.items[0]).toMatchObject({ name: 'Updated everyday shirt', material: 'Cotton', colours: ['White', 'Black'] })
    await page.getByRole('button', { name: 'Delete', exact: true }).click()
    await page.getByRole('dialog', { name: 'Remove this piece?' }).getByRole('button', { name: 'Delete piece', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'A little space for your favourite pieces' })).toBeVisible()
    await page.reload()
    expect((await (await page.request.get('/api/wardrobe/items')).json()).items).toHaveLength(0)
  })
})
